// #602: environment variables. Server code reads .env's variables from process.env (dev and build), the browser gets
// VITE_ ones through import.meta.env, and the `env` option names the required ones: the build fails without them, and
// .clarusjs/env.d.ts types them.
import { mkdirSync, mkdtempSync, readFileSync, readdirSync, symlinkSync, writeFileSync } from 'node:fs'
import { tmpdir } from 'node:os'
import { resolve } from 'node:path'
import { createBuilder } from 'vite'
import { afterEach, expect, test } from 'vitest'
import clarusjs, { type ClarusOptions } from '../../src/vite/plugin.ts'

function site(files: Record<string, string>) {
  const root = mkdtempSync(resolve(tmpdir(), 'clarus-env-'))
  for (const [path, text] of Object.entries(files)) { mkdirSync(resolve(root, path, '..'), { recursive: true }); writeFileSync(resolve(root, path), text) }
  mkdirSync(resolve(root, 'node_modules'))
  symlinkSync(resolve(import.meta.dirname, '../..'), resolve(root, 'node_modules/clarusjs'), 'junction')
  return root
}
const quiet = { info() {}, warn() {}, warnOnce() {}, error() {}, clearScreen() {}, hasErrorLogged: () => false, hasWarned: false }
const build = async (root: string, options: ClarusOptions = {}, mode?: string) =>
  (await createBuilder({ root, mode, configFile: false, customLogger: quiet, plugins: [clarusjs(options)] })).buildApp()
const page = (root: string) => readFileSync(resolve(root, 'dist/client/index.html'), 'utf8')
const js = (root: string) => readdirSync(resolve(root, 'dist/client/assets'), { recursive: true }).map(String).filter((f) => f.endsWith('.js')).map((f) => readFileSync(resolve(root, 'dist/client/assets', f), 'utf8')).join('\n')

const set: string[] = []
afterEach(() => { for (const k of set.splice(0)) delete process.env[k] })

test('.env files: server code reads every variable from process.env; the browser gets only VITE_ ones', async () => {
  set.push('CL_ENV_SECRET', 'CL_ENV_MODE_ONLY')
  const root = site({
    '.env': 'CL_ENV_SECRET=from-dotenv\nVITE_CL_PUBLIC=public-value\n',
    '.env.staging': 'CL_ENV_MODE_ONLY=staging-value\n',
    'src/pages/index.tscl': `<script server>
  const secret = process.env.CL_ENV_SECRET
  const staged = process.env.CL_ENV_MODE_ONLY
</script>
<p>{{ secret }} {{ staged }}</p>
<public-value />`,
    'src/components/public-value.tscl': `<script>
  let shown = state(import.meta.env.VITE_CL_PUBLIC)
</script>
<button (click)="shown = ''">{{ shown }}</button>`,
  })
  await build(root, {}, 'staging')
  expect(page(root)).toContain('from-dotenv staging-value')
  expect(js(root)).toContain('public-value')
  expect(js(root)).not.toContain('from-dotenv')
})

test('.env never overrides a variable already set (the host wins)', async () => {
  set.push('CL_ENV_SET')
  process.env.CL_ENV_SET = 'from-host'
  const root = site({ '.env': 'CL_ENV_SET=from-dotenv\n', 'src/pages/index.tscl': '<script server>const v = process.env.CL_ENV_SET</script>\n<p>{{ v }}</p>' })
  await build(root)
  expect(page(root)).toContain('from-host')
})

test('env: the build fails naming each missing variable; a browser one must start with VITE_', async () => {
  const root = site({ '.env': 'CL_ENV_HAVE=1\n', 'src/pages/index.tscl': '<p>Hi</p>' })
  await expect(build(root, { env: { server: ['CL_ENV_HAVE', 'CL_ENV_MISSING'], browser: ['VITE_CL_MISSING'] } })).rejects.toThrow(
    'clarusjs: missing environment variables: CL_ENV_MISSING (server), VITE_CL_MISSING (browser). Set them in the environment or a .env file (https://clarusjs.com/guide/environment-variables)',
  )
  await expect(build(root, { env: { browser: ['API_URL'] } })).rejects.toThrow("clarusjs: env.browser: 'API_URL' doesn't start with VITE_, so Vite won't send it to the browser")
})

test('env: .clarusjs/env.d.ts types the named variables as strings', async () => {
  set.push('CL_ENV_DB')
  const root = site({ '.env': 'CL_ENV_DB=postgres://x\nVITE_CL_API=https://api\n', 'src/pages/index.tscl': '<p>Hi</p>' })
  await build(root, { env: { server: ['CL_ENV_DB'], browser: ['VITE_CL_API'] } })
  expect(readFileSync(resolve(root, '.clarusjs/env.d.ts'), 'utf8')).toBe(
    '// Generated by clarusjs from the env option: the variables the build requires. Add it to your tsconfig\'s include.\n' +
    'interface ImportMetaEnv {\n  readonly VITE_CL_API: string\n}\n' +
    'interface ImportMeta {\n  readonly env: ImportMetaEnv\n}\n' +
    'declare namespace NodeJS {\n  interface ProcessEnv {\n    readonly CL_ENV_DB: string\n  }\n}\n',
  )
})
