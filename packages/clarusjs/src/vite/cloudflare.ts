// Cloudflare adapter (#604): a worker in dist/client/_worker.js/ (Pages' advanced mode) calling the same fetch handler
// for server routes, and _routes.json so Pages sends only those to it: static files (with _headers, _redirects and
// 404.html, which Pages reads itself) are served first. .assetsignore keeps the worker out of a Worker's static
// assets, so the same folder deploys as a Worker too. The server build is bundled (the plugin sets ssr.noExternal).
// @see https://developers.cloudflare.com/pages/functions/advanced-mode/
import { cpSync, rmSync, writeFileSync } from 'node:fs'
import { resolve } from 'node:path'
import { headersCode } from './headers.ts'

const WORKER = '_worker.js'

/** '/account/[id]' → ['/account/*']; '/api/hello' → ['/api/hello', '/api/hello/'] (Pages routes: * only). */
export function cloudflareRoutes(route: string, prefix: string, fragments = false): string[] {
  const segments = route.split('/')
  const at = segments.findIndex((seg) => /^\[[^\]]+\]$/.test(seg))
  // ponytail: a [param] becomes * for everything after it (Pages has no one-segment wildcard); the handler 404s the
  // rest. Pages allows 100 include rules: a site with more server routes should group them under a folder.
  if (at !== -1) return [`${prefix}${segments.slice(0, at).join('/')}/*`]
  const path = route === '/' ? '' : route
  return [...(path ? [`${prefix}${path}`] : []), `${prefix}${path}/`, ...(fragments ? [`${prefix}${path}/index.frag.html`] : [])]
}

export function writeCloudflareWorker(client: string, server: string, serverRoutes: string[], base: string, fragments = false): void {
  const worker = resolve(client, WORKER)
  const routesFile = resolve(client, '_routes.json')
  rmSync(worker, { recursive: true, force: true })
  rmSync(routesFile, { force: true })
  rmSync(resolve(client, '.assetsignore'), { force: true })
  const prefix = base.replace(/\/$/, '')
  // No server routes: static files only, which Pages serves itself, unless they sit under a base (the worker maps it).
  if (!serverRoutes.length && !prefix) return
  cpSync(server, resolve(worker, 'server'), { recursive: true })
  writeFileSync(resolve(worker, 'index.js'), [
    "// Generated by clarusjs: server routes on Cloudflare (Pages' _worker.js, or a Worker with static assets).",
    "import handler from './server/index.mjs'",
    `const base = ${JSON.stringify(prefix)}`,
    // Pages applies _headers to static files only: the worker applies them to what it answers.
    headersCode(client),
    'export default {',
    '  async fetch(request, env) {',
    '    const url = new URL(request.url)',
    "    // One path: runs of / collapsed, and a 400 for what decoding would turn into another path (dot segments, \\).",
    "    const path = url.pathname.replace(/\\/{2,}/g, '/')",
    '    let decoded',
    "    try { decoded = decodeURIComponent(path) } catch { return new Response('Bad Request: malformed URL', { status: 400 }) }",
    "    if (/\\\\|(^|\\/)\\.\\.?(\\/|$)/.test(decoded)) return new Response('Bad Request: malformed URL', { status: 400 })",
    "    const inBase = !base ? path : path === base ? '/' : path.startsWith(base + '/') ? path.slice(base.length) : undefined",
    '    if (inBase === undefined) return env.ASSETS.fetch(request)',
    '    url.pathname = inBase',
    '    // Not a server route: a static file, which sits at the folder\'s root, so without the base (a Worker without',
    '    // run_worker_first, a site under a base, or more server routes than _routes.json can list).',
    "    // _headers applied here by the path asked: Cloudflare would match them (written with the base) against the path",
    "    // without it, and may not apply them to what a worker returns. Only headers the file lacks are added.",
    '    if (!handler.isServerPath(inBase)) return withHeaders(await env.ASSETS.fetch(new Request(url, request)), path)',
    '    const response = await handler.fetch(new Request(url, request))',
    '    return withHeaders(response, path)',
    '  },',
    '}',
    '',
  ].join('\n'))
  // Pages serves the folder at the site's root: under a base, the worker takes the base's requests and serves its
  // static files from the root. Pages allows 100 rules of 100 characters at most: past that, it takes every request.
  const listed = serverRoutes.flatMap((r) => cloudflareRoutes(r, prefix, fragments))
  const wanted = prefix ? [prefix, `${prefix}/*`] : listed
  // Checked on the final list: a long base makes a long rule too.
  const include = wanted.length > 100 || wanted.some((r) => r.length > 100) ? ['/*'] : wanted
  writeFileSync(routesFile, JSON.stringify({ version: 1, include, exclude: [] }))
  writeFileSync(resolve(client, '.assetsignore'), `${WORKER}\n_routes.json\n`)
}
