// Vercel adapter (#603): the Build Output API (.vercel/output). dist/client becomes static/, server routes run as one
// Node function calling the same fetch handler, and config.json routes carry _headers, _redirects, clean URLs and
// the 404 page. The server build is bundled with its dependencies (the plugin sets ssr.noExternal), so the function
// needs nothing installed.
// @see https://vercel.com/docs/build-output-api/v3
import { cpSync, existsSync, readFileSync, readdirSync, rmSync, writeFileSync } from 'node:fs'
import { resolve } from 'node:path'
import { readHeaders } from './headers.ts'

const FUNCTION = 'clarusjs-server'
type Route = Record<string, unknown>
const escape = (s: string) => s.replace(/[.*+?^${}()|[\]\\]/g, '\\$&')

/** '/account/[id]' under '/docs' → '^/docs/account/[^/]+/?$' (and its fragment, with fragments on). */
export function vercelSource(route: string, prefix: string, fragments = false): string {
  const path = route === '/' ? '' : route.split('/').map((seg) => (/^\[[^\]]+\]$/.test(seg) ? '[^/]+' : escape(seg))).join('/')
  return `^${escape(prefix)}${path}/?${fragments ? '(?:index\\.frag\\.html)?' : ''}$`
}

export function writeVercelOutput(root: string, client: string, server: string, serverRoutes: string[], base: string, fragments = false): void {
  const prefix = base.replace(/\/$/, '')
  const output = resolve(root, '.vercel/output')
  rmSync(output, { recursive: true, force: true })
  // Static files, under the base. Not the host files (they become routes) or precompressed copies (Vercel compresses).
  const hostFiles = new Set(['_headers', '_redirects'])
  cpSync(client, resolve(output, 'static', `.${prefix}`), { recursive: true, filter: (src) => !hostFiles.has(src.slice(client.length + 1)) && !/\.(br|gz)$/.test(src) })
  // Clean URLs: a page's index.html answers at its path without the slash (the slash form is rewritten to it).
  const overrides: Record<string, { path: string }> = {}
  for (const file of readdirSync(client, { recursive: true }).map(String).map((f) => f.split('\\').join('/'))) {
    if (file !== 'index.html' && !file.endsWith('/index.html')) continue
    overrides[`${prefix.slice(1)}${prefix ? '/' : ''}${file}`] = { path: `${prefix.slice(1)}${prefix && file !== 'index.html' ? '/' : ''}${file.replace(/\/?index\.html$/, '')}` }
  }
  const routes: Route[] = [
    // _headers: on every response, static or not. Each rule takes its path's slash form too (parseHeaders), as the
    // slash rewrite below comes after.
    ...readHeaders(client).map((rule) => ({ src: rule.regex.source, headers: Object.fromEntries(rule.headers), continue: true })),
    // _redirects (`from to status`).
    ...(existsSync(resolve(client, '_redirects')) ? readFileSync(resolve(client, '_redirects'), 'utf8').split('\n') : [])
      .map((line) => line.trim().split(/\s+/))
      .filter((parts) => parts.length >= 2 && parts[0]!.startsWith('/'))
      .map(([from, to, status]) => ({ src: `^${escape(from!.replace(/\/$/, '') || '/')}/?$`, status: Number(status ?? 301), headers: { Location: to } })),
    { src: '^/(.+)/$', dest: '/$1' },
    { handle: 'filesystem' },
    ...serverRoutes.map((route) => ({ src: vercelSource(route, prefix, fragments), dest: `/${FUNCTION}` })),
    ...(existsSync(resolve(client, '404.html')) ? [{ handle: 'error' }, { src: '.*', status: 404, dest: `${prefix}/404.html` }] : []),
  ]
  writeFileSync(resolve(output, 'config.json'), JSON.stringify({ version: 3, routes, overrides }, null, 2))
  if (!serverRoutes.length) return
  const func = resolve(output, `functions/${FUNCTION}.func`)
  cpSync(server, resolve(func, 'server'), { recursive: true })
  writeFileSync(resolve(func, 'index.mjs'), [
    '// Generated by clarusjs: server routes on Vercel. The handler\'s routes are base-free.',
    "import handler from './server/index.mjs'",
    `const base = ${JSON.stringify(prefix)}`,
    'export default {',
    '  fetch(request) {',
    '    const url = new URL(request.url)',
    "    if (base && url.pathname.startsWith(base)) url.pathname = url.pathname.slice(base.length) || '/'",
    '    return handler.fetch(base ? new Request(url, request) : request)',
    '  },',
    '}',
    '',
  ].join('\n'))
  writeFileSync(resolve(func, '.vc-config.json'), JSON.stringify({ runtime: 'nodejs22.x', handler: 'index.mjs', launcherType: 'Nodejs', supportsResponseStreaming: true }, null, 2))
  writeFileSync(resolve(func, 'package.json'), JSON.stringify({ type: 'module' }))
}
