// Environment variables (#602): .env files for server code, and the `env` option's required variables, checked and
// typed. Vite loads .env files for the browser itself (VITE_ ones, in import.meta.env); server code reads
// process.env, which Vite leaves alone, so the plugin fills it from the same files. No vite import here: the CLI
// (clarusjs serve, in a production image without dev dependencies) imports this file.
import { mkdirSync, writeFileSync } from 'node:fs'
import { resolve } from 'node:path'

/** @see https://clarusjs.com/guide/environment-variables */
export type EnvOption = { server?: string[]; browser?: string[] }

/** The values this module put in process.env (not the host's), by name. */
const loaded = new Map<string, string>()

/**
 * Takes back what an earlier load put in process.env (a dev server restarted, a second build in one process): those
 * values are the plugin's, not the host's. Call it before Vite's loadEnv, which prefers process.env to the files. A
 * value the host changed since stays the host's.
 */
export function releaseServerEnv(): void {
  for (const [key, value] of loaded) if (process.env[key] === value) delete process.env[key]
  loaded.clear()
}

/**
 * `all`: Vite's loadEnv(mode, dir, '') (`.env`, `.env.local`, `.env.[mode]`, `.env.[mode].local`). Puts every variable
 * without a browser prefix in process.env for server code, unless already set (the host's value wins). Then checks the
 * `env` option: a missing variable is the returned message.
 */
export function loadServerEnv(all: Record<string, string>, prefixes: string[], required: EnvOption = {}): string | undefined {
  for (const [key, value] of Object.entries(all)) {
    if (!prefixes.some((p) => key.startsWith(p)) && process.env[key] === undefined) {
      process.env[key] = value
      loaded.set(key, value)
    }
  }
  for (const key of required.browser ?? []) {
    if (!prefixes.some((p) => key.startsWith(p))) throw new Error(`clarusjs: env.browser: '${key}' doesn't start with ${prefixes.join(' or ')}, so Vite won't send it to the browser`)
  }
  const missing = [
    ...(required.server ?? []).filter((k) => !process.env[k]).map((k) => `${k} (server)`),
    ...(required.browser ?? []).filter((k) => !all[k]).map((k) => `${k} (browser)`),
  ]
  return missing.length ? `clarusjs: missing environment variables: ${missing.join(', ')}. Set them in the environment or a .env file (https://clarusjs.com/guide/environment-variables)` : undefined
}

/** .clarusjs/env.d.ts: the named variables as strings, on import.meta.env and process.env. */
export function writeEnvTypes(root: string, env: EnvOption): void {
  const lines = (keys: string[] = [], indent: string) => keys.map((k) => `${indent}readonly ${k}: string\n`).join('')
  mkdirSync(resolve(root, '.clarusjs'), { recursive: true })
  writeFileSync(resolve(root, '.clarusjs/env.d.ts'),
    "// Generated by clarusjs from the env option: the variables the build requires. Add it to your tsconfig's include.\n" +
    `interface ImportMetaEnv {\n${lines(env.browser, '  ')}}\n` +
    'interface ImportMeta {\n  readonly env: ImportMetaEnv\n}\n' +
    `declare namespace NodeJS {\n  interface ProcessEnv {\n${lines(env.server, '    ')}  }\n}\n`)
}
